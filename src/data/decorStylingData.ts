export const getA7ProfessionalsByService = (serviceSlug?: string): Professional[] => {
  if (!serviceSlug || serviceSlug === 'all') return A7_PROFESSIONALS;
  return A7_PROFESSIONALS.filter((p) => p.servicesOffered.includes(serviceSlug));
};

