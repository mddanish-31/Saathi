export const getA3ProfessionalsByService = (serviceSlug?: string): Professional[] => {
    if (!serviceSlug) return A3_MOCK_PROFESSIONALS;
    return A3_MOCK_PROFESSIONALS.filter((pro) => pro.servicesOffered.includes(serviceSlug));
};

export const getA3ProfessionalById = (id: string): Professional | undefined => {
    return A3_MOCK_PROFESSIONALS.find((pro) => pro.id === id);
};

export const getA3ServiceBySlug = (slug: string): ServiceItem | undefined => {
    return A3_SERVICES.find((srv) => srv.slug === slug);
};
